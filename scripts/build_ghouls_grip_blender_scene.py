"""Build a reproducible Blender scene from the exact Ghoul's Grip master 3MF.

Blender owns presentation and explicitly approved organic refinements only.
Mechanical datums remain frozen and continue to be generated by the Python
sources in this repository.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

import bpy
from mathutils import Vector


ROOT = Path(__file__).resolve().parents[1]
SOURCE_3MF = ROOT / "models" / "ghouls-grip-master.3mf"
BLEND_PATH = ROOT / "model-sources" / "ghouls-grip" / "ghouls-grip-master.blend"
RENDER_PATH = ROOT / "docs" / "images" / "ghouls-grip-blender-master.png"

CORE = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"
NS = {"m": CORE}

ORGANIC_PREFIXES = (
    "forearm",
    "hand-palm",
    "hand-tendon-guide",
    "hand-finger",
    "trigger",
)


def _rgba(value: str) -> tuple[float, float, float, float]:
    value = value.removeprefix("#")
    if len(value) == 6:
        value += "FF"
    channels = tuple(int(value[index:index + 2], 16) / 255.0
                     for index in range(0, 8, 2))
    return channels


def _transform_vertex(
        vertex: tuple[float, float, float],
        transform: str | None,
) -> tuple[float, float, float]:
    if transform is None:
        return vertex
    values = [float(value) for value in transform.split()]
    if len(values) != 12:
        raise ValueError(f"Expected 12-value 3MF transform, got {transform!r}")
    x, y, z = vertex
    return (
        x * values[0] + y * values[3] + z * values[6] + values[9],
        x * values[1] + y * values[4] + z * values[7] + values[10],
        x * values[2] + y * values[5] + z * values[8] + values[11],
    )


def _look_at(camera: bpy.types.Object, target: Vector) -> None:
    camera.rotation_euler = (target - camera.location).to_track_quat(
        "-Z", "Y").to_euler()


def _material(name: str, display_color: str) -> bpy.types.Material:
    material = bpy.data.materials.new(name=name)
    material.diffuse_color = _rgba(display_color)
    material.use_nodes = True
    shader = material.node_tree.nodes.get("Principled BSDF")
    shader.inputs["Base Color"].default_value = material.diffuse_color
    shader.inputs["Roughness"].default_value = 0.47
    shader.inputs["Metallic"].default_value = 0.0
    return material


def _reset_scene() -> None:
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for collection in list(bpy.data.collections):
        if collection.name != "Collection":
            bpy.data.collections.remove(collection)
    root = bpy.context.scene.collection
    default = bpy.data.collections.get("Collection")
    if default is not None:
        default.name = "Presentation"
    for name in ("frozen_technical", "organic_approved"):
        collection = bpy.data.collections.new(name)
        root.children.link(collection)


def _link_to_collection(obj: bpy.types.Object, collection_name: str) -> None:
    for collection in list(obj.users_collection):
        collection.objects.unlink(obj)
    bpy.data.collections[collection_name].objects.link(obj)


def _import_master() -> list[bpy.types.Object]:
    with ZipFile(SOURCE_3MF) as archive:
        root = ET.fromstring(archive.read("3D/3dmodel.model"))

    bases = root.findall(".//m:resources/m:basematerials/m:base", NS)
    materials = [
        _material(base.get("name", f"material-{index}"),
                  base.get("displaycolor", "#B0B0B0FF"))
        for index, base in enumerate(bases)
    ]
    objects = {
        node.get("id"): node
        for node in root.findall(".//m:resources/m:object", NS)
    }

    imported = []
    for item in root.findall(".//m:build/m:item", NS):
        node = objects[item.get("objectid")]
        name = node.get("name", f"object-{item.get('objectid')}")
        mesh_node = node.find("m:mesh", NS)
        if mesh_node is None:
            continue
        vertices = [
            _transform_vertex(
                (
                    float(vertex.get("x")),
                    float(vertex.get("y")),
                    float(vertex.get("z")),
                ),
                item.get("transform"),
            )
            for vertex in mesh_node.findall("m:vertices/m:vertex", NS)
        ]
        faces = [
            (
                int(triangle.get("v1")),
                int(triangle.get("v2")),
                int(triangle.get("v3")),
            )
            for triangle in mesh_node.findall("m:triangles/m:triangle", NS)
        ]
        organic = name.startswith(ORGANIC_PREFIXES)
        role = "organic" if organic else "frozen"
        mesh = bpy.data.meshes.new(f"{role}_{name}_mesh")
        mesh.from_pydata(vertices, [], faces)
        mesh.update(calc_edges=True)

        obj = bpy.data.objects.new(f"{role}_{name}", mesh)
        collection = "organic_approved" if organic else "frozen_technical"
        bpy.data.collections[collection].objects.link(obj)
        obj.data.materials.append(materials[int(node.get("pindex", "0"))])
        obj["source_3mf"] = SOURCE_3MF.name
        obj["source_name"] = name
        obj["geometry_owner"] = (
            "Blender visual region; validate before export"
            if organic else
            "Python source of truth; do not modify in Blender"
        )
        obj.hide_select = not organic
        imported.append(obj)
    return imported


def _scene_bounds(objects: list[bpy.types.Object]) -> tuple[Vector, Vector]:
    points = [
        obj.matrix_world @ Vector(corner)
        for obj in objects
        for corner in obj.bound_box
    ]
    low = Vector(tuple(min(point[axis] for point in points)
                       for axis in range(3)))
    high = Vector(tuple(max(point[axis] for point in points)
                        for axis in range(3)))
    return low, high


def _add_presentation(bounds: tuple[Vector, Vector]) -> None:
    low, high = bounds
    center = (low + high) / 2.0
    size = high - low
    presentation = bpy.data.collections["Presentation"]

    bpy.ops.mesh.primitive_plane_add(
        size=max(size.x, size.y) * 1.65,
        location=(center.x, center.y, low.z - 0.25),
    )
    floor = bpy.context.object
    floor.name = "presentation_floor"
    _link_to_collection(floor, presentation.name)
    floor_material = _material("presentation_floor", "#141016FF")
    floor.data.materials.append(floor_material)

    camera_data = bpy.data.cameras.new("presentation_camera")
    camera = bpy.data.objects.new("presentation_camera", camera_data)
    presentation.objects.link(camera)
    camera.location = (
        center.x + size.x * 1.15,
        center.y - size.y * 1.65,
        center.z + size.z * 0.85,
    )
    _look_at(camera, center + Vector((0.0, 0.0, size.z * 0.08)))
    camera.data.lens = 58
    bpy.context.scene.camera = camera

    for name, location, energy, radius, color in (
        (
            "key_light",
            (center.x - size.x * 0.7, center.y - size.y, high.z + size.z),
            1300,
            90,
            (1.0, 0.72, 0.48),
        ),
        (
            "fill_light",
            (center.x + size.x, center.y + size.y * 0.2, center.z),
            900,
            70,
            (0.40, 0.55, 1.0),
        ),
        (
            "rim_light",
            (center.x - size.x, center.y + size.y, high.z),
            1100,
            65,
            (0.58, 0.75, 1.0),
        ),
    ):
        light_data = bpy.data.lights.new(name=name, type="AREA")
        light_data.energy = energy
        light_data.shape = "DISK"
        light_data.size = radius
        light_data.color = color
        light = bpy.data.objects.new(name, light_data)
        light.location = location
        _look_at(light, center)
        presentation.objects.link(light)


def main() -> None:
    if not SOURCE_3MF.exists():
        raise FileNotFoundError(SOURCE_3MF)
    BLEND_PATH.parent.mkdir(parents=True, exist_ok=True)
    RENDER_PATH.parent.mkdir(parents=True, exist_ok=True)

    _reset_scene()
    scene = bpy.context.scene
    scene.unit_settings.system = "METRIC"
    scene.unit_settings.length_unit = "MILLIMETERS"
    scene.unit_settings.scale_length = 0.001
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.render.resolution_x = 1000
    scene.render.resolution_y = 850
    scene.render.resolution_percentage = 100
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = str(RENDER_PATH)
    scene.render.film_transparent = False
    scene.world.color = (0.025, 0.02, 0.035)
    scene.display.shading.light = "STUDIO"
    scene.display.shading.color_type = "MATERIAL"
    scene.display.shading.show_shadows = True
    scene.display.shading.show_cavity = True
    scene.display.shading.cavity_type = "WORLD"
    scene.display.shading.show_specular_highlight = True
    scene.display.shading.background_type = "WORLD"

    imported = _import_master()
    bounds = _scene_bounds(imported)
    _add_presentation(bounds)

    scene["source_3mf"] = str(SOURCE_3MF.relative_to(ROOT))
    scene["geometry_contract"] = (
        "Python owns fit-critical geometry; Blender owns approved visual regions."
    )
    scene["frozen_collection"] = "frozen_technical"
    scene["editable_collection"] = "organic_approved"

    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND_PATH))
    bpy.ops.render.render(write_still=True)

    low, high = bounds
    print(f"BLEND={BLEND_PATH}")
    print(f"RENDER={RENDER_PATH}")
    print(f"OBJECTS={len(imported)}")
    print(
        "BOUNDS_MM="
        f"{tuple(round(value, 3) for value in low)} -> "
        f"{tuple(round(value, 3) for value in high)}"
    )


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)
